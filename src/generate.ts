import path from 'node:path';
import { randomUUID } from 'node:crypto';
import {
  cp,
  mkdir,
  mkdtemp,
  readFile,
  rename,
  rm,
  writeFile,
  lstat,
  realpath,
} from 'node:fs/promises';
import { Gtfs } from 'gtfs';
import type { GtfsReportEvent } from 'gtfs';
import type {
  ChartConfig,
  ChartResult,
  ChartSourceResult,
  GenerateChartsOptions,
} from './types.ts';
import { resolveConfig, resolvePath } from './config/config.ts';
import { getChartData } from './chart/data.ts';
import { fileId, renderChart, renderOverview, root } from './output/render.ts';

const marker = '.gtfs-to-chart.json';

async function exists(filename: string): Promise<boolean> {
  try {
    await lstat(filename);
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      return false;
    }
    throw error;
  }
}

async function canonicalPath(filename: string): Promise<string> {
  try {
    return await realpath(filename);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      throw error;
    }
    return path.join(
      await canonicalPath(path.dirname(filename)),
      path.basename(filename),
    );
  }
}

/** Import GTFS and atomically publish a directory of interactive HTML charts. */
export async function generateCharts(
  input: ChartConfig,
  options: GenerateChartsOptions = {},
): Promise<ChartResult> {
  for (const key of Object.keys(options)) {
    if (key !== 'import') {
      throw new Error(`Unknown generation option: ${key}`);
    }
  }
  if (options.import !== undefined && typeof options.import !== 'boolean') {
    throw new Error('import must be a boolean');
  }
  const config = resolveConfig(input);
  if (
    options.import === false &&
    !('client' in config.gtfs.database) &&
    (!config.gtfs.database.path || config.gtfs.database.path === ':memory:')
  ) {
    throw new Error('import: false requires a persistent database');
  }
  const destination = config.output.directory;
  // Never replace the working directory or one of its parents.
  const canonicalDestination = await canonicalPath(destination);
  const relative = path.relative(
    canonicalDestination,
    await realpath(process.cwd()),
  );
  if (
    !relative.startsWith(`..${path.sep}`) &&
    relative !== '..' &&
    !path.isAbsolute(relative)
  ) {
    throw new Error('output.directory must not contain the working directory');
  }
  const protectedPaths = [
    ...('path' in config.gtfs.database &&
    config.gtfs.database.path !== ':memory:'
      ? [config.gtfs.database.path]
      : []),
    ...config.gtfs.sources.flatMap((source) =>
      source.schedule && 'path' in source.schedule
        ? [source.schedule.path]
        : [],
    ),
    ...(config.output.templateDirectory
      ? [config.output.templateDirectory]
      : []),
    root,
  ];
  for (const protectedPath of protectedPaths) {
    const relative = path.relative(
      canonicalDestination,
      await canonicalPath(resolvePath(protectedPath)),
    );
    if (
      relative === '' ||
      (!relative.startsWith(`..${path.sep}`) &&
        relative !== '..' &&
        !path.isAbsolute(relative))
    ) {
      throw new Error(
        'output.directory must not contain the database, input feed, templates, or installed package',
      );
    }
  }
  const existed = await exists(destination);
  if (existed) {
    if (!config.output.overwrite) {
      throw new Error(
        `Output already exists: ${destination}; set output.overwrite to true`,
      );
    }
    const stat = await lstat(destination);
    if (stat.isSymbolicLink() || !stat.isDirectory()) {
      throw new Error('Output must be a real directory');
    }
    let owned = false;
    try {
      owned =
        JSON.parse(await readFile(path.join(destination, marker), 'utf8'))
          .generator === 'gtfs-to-chart';
    } catch {
      // Unmarked directories must never be deleted as generated output.
    }
    if (!owned) {
      throw new Error(
        'Refusing to overwrite a directory not generated by gtfs-to-chart v3',
      );
    }
  }
  const start = performance.now();
  const operationId = randomUUID();
  const report = (
    message: string,
    phase: 'start' | 'complete',
    sourceId?: string,
  ) => {
    if (
      input.reporting?.reporter &&
      (input.reporting.level === undefined || input.reporting.level === 'info')
    ) {
      const event: GtfsReportEvent = {
        type: 'status',
        level: 'info',
        timestampMs: Date.now(),
        operationId,
        message,
        phase,
        progressBar: false,
        ...(sourceId === undefined ? {} : { sourceId }),
      };
      input.reporting.reporter(event);
    }
  };
  const gtfs = new Gtfs(config.gtfs);
  let staging: string | undefined;
  try {
    if (options.import !== false) {
      const result = await gtfs.import();
      if (!result.success) {
        throw new Error(`GTFS import failed: ${JSON.stringify(result.errors)}`);
      }
    }
    await mkdir(path.dirname(destination), { recursive: true });
    staging = await mkdtemp(
      path.join(path.dirname(destination), '.gtfs-to-chart-'),
    );
    await cp(path.join(root, 'assets'), staging, { recursive: true });
    const results: ChartSourceResult[] = [];
    for (const source of config.gtfs.sources) {
      report(
        `Generating charts for ${source.sourceId}`,
        'start',
        source.sourceId,
      );
      const sourceDirectory = fileId(source.sourceId);
      await mkdir(path.join(staging, sourceDirectory, 'routes'), {
        recursive: true,
      });
      const routes = await gtfs.schedule.routes
        .where({ source_id: source.sourceId })
        .all();
      if (routes.length === 0) {
        throw new Error(`No imported routes for source ${source.sourceId}`);
      }
      for (const routeId of config.charts.routeIds ?? []) {
        if (!routes.some((route) => route.route_id === routeId)) {
          throw new Error(
            `Unknown route ${routeId} in source ${source.sourceId}`,
          );
        }
      }
      const generated = [];
      const skippedRouteIds = [];
      for (const route of routes) {
        if (
          config.charts.routeIds !== undefined &&
          !config.charts.routeIds.includes(route.route_id)
        ) {
          continue;
        }
        const data = await getChartData(
          gtfs,
          source.sourceId,
          config.charts,
          route.route_id,
        );
        if (data === null) {
          skippedRouteIds.push(route.route_id);
          continue;
        }
        await writeFile(
          path.join(
            staging,
            sourceDirectory,
            'routes',
            `${fileId(route.route_id)}.html`,
          ),
          renderChart(route, data, config),
        );
        generated.push(route);
      }
      await writeFile(
        path.join(staging, sourceDirectory, 'index.html'),
        await renderOverview(gtfs, source.sourceId, generated, config),
      );
      results.push({
        sourceId: source.sourceId,
        directory: path.join(destination, sourceDirectory),
        charts: generated.length,
        skippedRouteIds,
      });
      report(
        `${source.sourceId}: ${generated.length} charts; ${skippedRouteIds.length} routes without service`,
        'complete',
        source.sourceId,
      );
    }
    const escape = (value: string) =>
      value
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('"', '&quot;');
    await writeFile(
      path.join(staging, 'index.html'),
      `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Transit charts</title><h1>Transit charts</h1><ul>${results.map((source) => `<li><a href="${fileId(source.sourceId)}/index.html">${escape(source.sourceId)}</a> (${source.charts} charts)</li>`).join('')}</ul></html>`,
    );
    await writeFile(
      path.join(staging, marker),
      JSON.stringify({
        generator: 'gtfs-to-chart',
        serviceDate: config.charts.serviceDate,
      }),
    );
    // Close before publishing so database cleanup failure cannot report a false success.
    await gtfs.close();
    const backup = `${staging}-previous`;
    if (existed) {
      await rename(destination, backup);
    } else if (await exists(destination)) {
      throw new Error(`Output appeared during generation: ${destination}`);
    }
    try {
      await rename(staging, destination);
      staging = undefined;
    } catch (error) {
      if (existed) {
        await rename(backup, destination);
      }
      throw error;
    }
    if (existed) {
      await rm(backup, { recursive: true, force: true });
    }
    report(`Charts written to ${destination}`, 'complete');
    return {
      success: true,
      directory: destination,
      sources: results,
      durationMs: Math.round(performance.now() - start),
    };
  } finally {
    try {
      if (!gtfs.isClosed) {
        await gtfs.close();
      }
    } finally {
      if (staging) {
        await rm(staging, { recursive: true, force: true });
      }
    }
  }
}
