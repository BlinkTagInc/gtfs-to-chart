import type {
  GtfsConfig,
  GtfsInstanceSourceConfig,
  GtfsExtensionSelection,
} from 'gtfs';

/** node-GTFS v5 configuration plus chart generation settings. */
export interface ChartConfig extends Omit<
  GtfsConfig,
  'sources' | 'export' | 'extensions'
> {
  readonly extensions?: GtfsExtensionSelection;
  readonly sources: readonly (
    GtfsConfig['sources'][number] | GtfsInstanceSourceConfig
  )[];
  readonly charts?: {
    /** GTFS service date, YYYYMMDD; defaults to today in the local timezone. */
    readonly serviceDate?: number;
    /** Restrict generation to these route IDs in each source. */
    readonly routeIds?: readonly string[];
    /** Include only timed stops marked as timepoints. Defaults to true. */
    readonly timepointsOnly?: boolean;
  };
  readonly output?: {
    readonly directory?: string;
    /** Replace a directory previously generated by this library. Defaults to false. */
    readonly overwrite?: boolean;
    readonly templateDirectory?: string;
    readonly pretty?: boolean;
  };
}

export interface GenerateChartsOptions {
  /** Use data already stored in the configured database. */
  readonly import?: boolean;
}

export interface ChartSourceResult {
  readonly sourceId: string;
  readonly directory: string;
  readonly charts: number;
  readonly skippedRouteIds: readonly string[];
}

export interface ChartResult {
  readonly success: true;
  readonly directory: string;
  readonly extensions?: GtfsExtensionSelection;
  readonly sources: readonly ChartSourceResult[];
  readonly durationMs: number;
}

export interface StopTime {
  arrival_time: string;
  departure_time: string;
  stop_id: string;
  shape_dist_traveled: number | null;
  timepoint: number | null;
}

export interface ChartTrip {
  trip_id: string;
  trip_headsign: string | null;
  direction_id: number | null;
  stoptimes: StopTime[];
}

export interface Station {
  stop_id: string;
  name: string;
  distance: number;
  direction_id: number | null;
}

export interface ChartData {
  trips: ChartTrip[];
  stations: Station[];
  notes: string[];
}
